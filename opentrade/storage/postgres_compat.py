"""PostgreSQL compatibility translation and connection/cursor wrappers (psycopg v3)."""

import re
from pathlib import Path
from typing import Any

_AUTOINC_RE = re.compile(
    r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
    re.IGNORECASE,
)
_INSERT_IGNORE_RE = re.compile(
    r"\bINSERT\s+OR\s+IGNORE\s+INTO\b",
    re.IGNORECASE,
)
_SERIAL_INSERT_RE = re.compile(
    r"^\s*INSERT\s+INTO\s+(users|auth_tokens|sessions|chat_messages|subscriptions)\b",
    re.IGNORECASE,
)


def is_postgres_url(value: str | Path | None) -> bool:
    """Return True if value is a PostgreSQL connection URI."""
    if value is None:
        return False
    text = str(value).strip().lower()
    return text.startswith(("postgresql://", "postgres://"))


def _replace_qmark_outside_quotes(sql: str) -> str:
    """Replace SQLite '?' placeholders with psycopg '%s' outside single quotes."""
    out: list[str] = []
    in_quote = False
    i = 0
    n = len(sql)
    while i < n:
        ch = sql[i]
        if ch == "'":
            out.append(ch)
            if in_quote and i + 1 < n and sql[i + 1] == "'":
                out.append("'")
                i += 2
                continue
            in_quote = not in_quote
        elif ch == "?" and not in_quote:
            out.append("%s")
        else:
            out.append(ch)
        i += 1
    return "".join(out)


def translate_sql_to_postgres(sql: str) -> str:
    """Translate SQLite-flavored SQL/DDL into PostgreSQL-compatible SQL."""
    translated = _AUTOINC_RE.sub(
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        sql,
    )
    if _INSERT_IGNORE_RE.search(translated):
        translated = _INSERT_IGNORE_RE.sub("INSERT INTO", translated)
        stripped = translated.rstrip()
        if stripped.endswith(";"):
            translated = f"{stripped[:-1]} ON CONFLICT DO NOTHING;"
        else:
            translated = f"{stripped} ON CONFLICT DO NOTHING"
    return _replace_qmark_outside_quotes(translated)


class PostgresCursorWrapper:
    """Wraps a psycopg cursor to expose sqlite3-compatible execute/lastrowid/fetch APIs."""

    def __init__(self, cursor: Any) -> None:
        self._cursor = cursor
        self.lastrowid: int | None = None

    def execute(
        self, sql: str, params: tuple[Any, ...] | list[Any] = ()
    ) -> "PostgresCursorWrapper":
        pg_sql = translate_sql_to_postgres(sql)
        needs_id = bool(_SERIAL_INSERT_RE.match(pg_sql)) and "RETURNING" not in pg_sql.upper()
        if needs_id:
            stripped = pg_sql.rstrip()
            pg_sql = (
                f"{stripped[:-1]} RETURNING id;"
                if stripped.endswith(";")
                else f"{stripped} RETURNING id"
            )
        self._cursor.execute(pg_sql, params or None)
        if needs_id:
            row = self._cursor.fetchone()
            self.lastrowid = int(row[0]) if row else None
        else:
            self.lastrowid = None
        return self

    def fetchone(self) -> Any:
        return self._cursor.fetchone()

    def fetchall(self) -> list[Any]:
        return list(self._cursor.fetchall())

    def close(self) -> None:
        self._cursor.close()


class PostgresConnectionWrapper:
    """Wraps a psycopg connection to expose sqlite3-compatible cursor/execute/tx APIs."""

    def __init__(self, conn: Any) -> None:
        self._conn = conn

    def cursor(self) -> PostgresCursorWrapper:
        return PostgresCursorWrapper(self._conn.cursor())

    def execute(self, sql: str, params: tuple[Any, ...] | list[Any] = ()) -> PostgresCursorWrapper:
        cur = self.cursor()
        return cur.execute(sql, params)

    def commit(self) -> None:
        self._conn.commit()

    def rollback(self) -> None:
        self._conn.rollback()

    def close(self) -> None:
        self._conn.close()
