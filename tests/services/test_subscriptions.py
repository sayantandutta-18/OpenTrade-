"""Unit tests for Terms acceptance persistence and INR Subscription service."""

from datetime import UTC, datetime, timedelta
from pathlib import Path

import pytest

from opentrade.services.auth import clear_login_ip_rate_limits, register_endpoint
from opentrade.services.errors import ValidationError
from opentrade.services.subscription_service import (
    SUBSCRIPTION_PLANS,
    activate_subscription,
    cancel_user_subscription,
    get_user_subscription_status,
    list_plans,
)
from opentrade.storage.db import get_connection
from opentrade.storage.migrate import run_migrations
from opentrade.storage.postgres_compat import translate_sql_to_postgres
from opentrade.storage.repositories import UserRepository


def test_inr_plans_pricing_and_postgres_sql_translation() -> None:
    """Verify the 3 INR plans and PostgreSQL SQL translation for subscriptions."""
    plans = list_plans()
    assert [p.code for p in plans] == ["monthly_999", "half_yearly_3999", "yearly_7999"]
    assert SUBSCRIPTION_PLANS["monthly_999"].amount_inr == 999
    assert SUBSCRIPTION_PLANS["half_yearly_3999"].amount_inr == 3999
    assert SUBSCRIPTION_PLANS["yearly_7999"].amount_inr == 7999

    ddl = translate_sql_to_postgres(
        "CREATE TABLE subscriptions (id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER);"
    )
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl


def test_terms_accepted_at_and_subscription_lifecycle(tmp_path: Path) -> None:
    """Verify terms_accepted_at persistence, plan activation, upgrade, expiry, and cancel."""
    clear_login_ip_rate_limits()
    db_path = tmp_path / "subs.db"
    run_migrations(db_path)

    status_code, _ = register_endpoint(
        {
            "name": "Priya Quant",
            "email": "priya@example.com",
            "password": "VeryStrongPassword99!",
            "terms_accepted": True,
        },
        db_path=db_path,
    )
    assert status_code == 201

    conn = get_connection(db_path)
    try:
        user = UserRepository(conn).get_by_email("priya@example.com")
        assert user is not None
        assert user.terms_accepted_at is not None

        t0 = datetime(2026, 1, 1, 12, 0, tzinfo=UTC)
        # Initially Free / Demo
        s0 = get_user_subscription_status(conn, user.id, now=t0)
        assert s0["is_pro"] is False
        assert s0["tier"] == "Free / Demo"

        # Invalid plan raises ValidationError
        with pytest.raises(ValidationError, match="Unknown subscription plan"):
            activate_subscription(conn, user.id, "invalid_plan", now=t0)

        # Activate Pro Monthly (₹999 / 30 days)
        sub1 = activate_subscription(conn, user.id, "monthly_999", payment_ref="rzp_123", now=t0)
        assert sub1["amount_inr"] == 999
        assert sub1["payment_ref"] == "rzp_123"
        s1 = get_user_subscription_status(conn, user.id, now=t0 + timedelta(days=5))
        assert s1["is_pro"] is True
        assert s1["tier"] == "Pro Monthly"
        assert s1["days_remaining"] == 25

        # Upgrade to Pro Annual (₹7,999 / 365 days) cancels prior active plan
        sub2 = activate_subscription(conn, user.id, "yearly_7999", now=t0 + timedelta(days=5))
        assert sub2["amount_inr"] == 7999
        s2 = get_user_subscription_status(conn, user.id, now=t0 + timedelta(days=10))
        assert s2["is_pro"] is True
        assert s2["tier"] == "Pro Annual"
        assert len(s2["history"]) == 2
        assert s2["history"][1]["status"] == "cancelled"

        # Cancel active plan
        cancel_user_subscription(conn, user.id)
        s3 = get_user_subscription_status(conn, user.id, now=t0 + timedelta(days=10))
        assert s3["is_pro"] is False
    finally:
        conn.close()
